def activate(lang: str):
    """Переключает язык промптов на весь прогон: "ru" (как в проде) или "en" (публичные бенчи).

    Подменяет значения в этом модуле, поэтому pipeline/llm продолжают читать prompts.X и получают
    нужный язык. Вызывать один раз перед прогоном.
    """
    if lang == "ru":
        return [(c, d) for c, d in _TOPICS_RU]
    if lang != "en":
        raise ValueError(f"неизвестный язык промптов: {lang}")
    from . import prompts_en
    g = globals()
    for name in ("COLLECT_PROMPT", "MEMORY_PROMPT", "TOPIC_PROMPT", "COLLECT_SCHEMA_HINT", "MEMORY_SCHEMA_HINT",
                 "TOPIC_SCHEMA_HINT", "FUNCTION_NAME", "FUNCTION_DESCRIPTION_BEFORE", "FUNCTION_DESCRIPTION_AFTER",
                 "TOPIC_PARAM_BEFORE", "TOPIC_PARAM_AFTER", "AGENT_SYSTEM_PROMPT"):
        g[name] = getattr(prompts_en, name)
    # целевая схема (шаги 2–6): те же правила по-английски
    from . import prompts_profile, prompts_profile_en
    for name in ("L", "AGENT_SYSTEM_PROMPT_PROFILE", "FACTS_HEADER", "PROFILE_HEADER", "PROFILE_EMPTY", "RECENT_HEADER",
                 "CLAIM_RULE", "COLLECT_PROMPT_CTX", "SECTIONS_HELP", "OPS_HELP", "SESSION_PROMPT", "SESSION_SCHEMA_HINT",
                 "SLEEP_PROMPT", "COMMAND_PROMPT", "REMEMBER_FUNCTION", "FORGET_FUNCTION", "SEARCH_HINT",
                 "SEARCH_FUNCTION"):
        setattr(prompts_profile, name, getattr(prompts_profile_en, name))
    return list(prompts_en.TOPICS)
